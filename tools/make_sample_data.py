"""Generate the fictional, deliberately messy branch sales exports used by this demo.

6 branches x 3 months (Jul-Sep 2026) = 18 files. Every branch exports differently, the way
real point-of-sale systems do:

  Amsterdam Centrum  clean CSV
  Amsterdam Oost     ; separated, Dutch headers and product names, decimal commas, dd-mm-yyyy
  Utrecht            Excel with title rows on top and blank rows in between
  Rotterdam          Excel with typos in product names, weekly subtotal rows, a grand total, one typo in a quantity
  Den Haag           CSV with US dates (mm/dd/yyyy), "€" in amounts, and rows exported twice
  Haarlem            Excel with columns in another order, "2 pcs" quantities and no price column

    python tools/make_sample_data.py          # writes to sample_data/
"""
import calendar
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pandas as pd
from openpyxl import Workbook

OUT = Path(__file__).resolve().parents[1] / "sample_data"
RNG = np.random.default_rng(42)

PRODUCTS = {  # name: (price, base daily units for an average branch)
    "Espresso": (2.60, 22), "Americano": (3.10, 18), "Cappuccino": (3.60, 34), "Latte": (3.90, 38),
    "Flat White": (4.10, 20), "Tea": (2.80, 12), "Hot Chocolate": (3.70, 9), "Croissant": (2.90, 26),
    "Banana Bread": (3.50, 11), "Sandwich": (6.50, 15),
}
BRANCHES = {"Amsterdam Centrum": 1.45, "Amsterdam Oost": 0.95, "Utrecht": 1.15, "Rotterdam": 1.05,
            "Den Haag": 0.85, "Haarlem": 0.70}
MONTH_TREND = {7: 0.94, 8: 0.97, 9: 1.08}     # summer dip, busy September
WEEKDAY = [0.92, 0.95, 0.97, 1.0, 1.08, 1.22, 1.12]
DUTCH = {"Latte": "Koffie verkeerd", "Tea": "Thee", "Hot Chocolate": "Warme chocolademelk",
         "Banana Bread": "Bananenbrood", "Sandwich": "Broodje"}
TYPOS = {"Cappuccino": ["cappucino", "Cappuccino", "CAPPUCCINO"], "Espresso": ["Expresso", "espresso"],
         "Croissant": ["Croisant", "croissant"], "Flat White": ["Flat white ", "flatwhite"], "Latte": ["LATTE", "Latte "]}


def daily_sales(branch: str, year: int, month: int) -> pd.DataFrame:
    rows = []
    for day in range(1, calendar.monthrange(year, month)[1] + 1):
        d = date(year, month, day)
        factor = BRANCHES[branch] * MONTH_TREND[month] * WEEKDAY[d.weekday()]
        for product, (price, base) in PRODUCTS.items():
            qty = int(RNG.poisson(base * factor))
            rows.append({"date": d, "product": product, "qty": qty, "price": price, "revenue": round(qty * price, 2)})
    return pd.DataFrame(rows)


def nl(v: float) -> str:
    return f"{v:.2f}".replace(".", ",")


def centrum(df, month, path):
    out = df.rename(columns={"date": "Date", "product": "Product", "qty": "Qty", "price": "Unit Price",
                             "revenue": "Total"})
    out.to_csv(path / f"AMS-Centrum_2026-{month:02d}.csv", index=False)


def oost(df, month, path):
    out = pd.DataFrame({
        "Datum": df["date"].map(lambda d: d.strftime("%d-%m-%Y")),
        "Product": df["product"].map(lambda p: DUTCH.get(p, p)),
        "Aantal": df["qty"], "Prijs": df["price"].map(nl), "Omzet": df["revenue"].map(nl)})
    name = {7: "juli", 8: "augustus", 9: "september"}[month]
    out.to_csv(path / f"oost {name} 2026.csv", index=False, sep=";")


def utrecht(df, month, path):
    wb = Workbook()
    ws = wb.active
    ws.title = "Export"
    ws.append([f"Sales export - Utrecht - {calendar.month_name[month]} 2026"])
    ws.append(["Generated by POS v4.2"])
    ws.append([])
    ws.append(["Sale Date", "Item", "Units", "Price (€)", "Revenue"])
    for i, r in enumerate(df.itertuples()):
        if i and i % 97 == 0:
            ws.append([])                                   # stray blank rows
        ws.append([r.date, r.product, r.qty, r.price, r.revenue])
        ws.cell(ws.max_row, 1).number_format = "dd/mm/yyyy"
    wb.save(path / f"Utrecht sales {calendar.month_name[month]} 2026.xlsx")


def rotterdam(df, month, path):
    wb = Workbook()
    ws = wb.active
    ws.append(["date", "product", "quantity", "price", "amount"])
    week, week_total, grand = None, 0.0, 0.0
    for r in df.itertuples():
        iso_week = r.date.isocalendar()[1]
        if week is not None and iso_week != week:
            ws.append([None, f"Week {week} total", None, None, round(week_total, 2)])
            week_total = 0.0
        week = iso_week
        product = RNG.choice(TYPOS[r.product]) if r.product in TYPOS and RNG.random() < 0.35 else r.product
        qty = r.qty
        if month == 8 and r.date.day == 14 and r.product == "Latte":
            qty = r.qty * 10                                # typed 380 instead of 38
        ws.append([r.date, product, qty, r.price, round(qty * r.price, 2)])
        ws.cell(ws.max_row, 1).number_format = "yyyy-mm-dd"
        week_total += qty * r.price
        grand += qty * r.price
    ws.append([None, f"Week {week} total", None, None, round(week_total, 2)])
    ws.append([])
    ws.append([None, "GRAND TOTAL", None, None, round(grand, 2)])
    wb.save(path / f"ROTTERDAM_{month:02d}_2026.xlsx")


def den_haag(df, month, path):
    out = pd.DataFrame({
        "Transaction Date": df["date"].map(lambda d: d.strftime("%m/%d/%Y")),
        "Product Name": df["product"], "Qty Sold": df["qty"],
        "Unit Price": df["price"].map(lambda v: f"€{v:.2f}"), "Sales": df["revenue"].map(lambda v: f"€{v:.2f}")})
    if month == 9:                                          # the POS exported the 20th-21st twice
        repeat = out[out["Transaction Date"].isin(["09/20/2026", "09/21/2026"])]
        out = pd.concat([out, repeat], ignore_index=True)
    last_day = calendar.monthrange(2026, month)[1]
    out.to_csv(path / f"DenHaag-export-2026-{month:02d}-{last_day}.csv", index=False)


def haarlem(df, month, path):
    wb = Workbook()
    ws = wb.active
    ws.append(["Product", "Total", "Qty", "Day"])
    for r in df.itertuples():
        ws.append([r.product, r.revenue, f"{r.qty} pcs", r.date.isoformat()])
    wb.save(path / f"Haarlem {calendar.month_abbr[month]}26.xlsx")


WRITERS = {"Amsterdam Centrum": centrum, "Amsterdam Oost": oost, "Utrecht": utrecht, "Rotterdam": rotterdam,
           "Den Haag": den_haag, "Haarlem": haarlem}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for f in OUT.iterdir():
        f.unlink()
    for month in (7, 8, 9):
        for branch, writer in WRITERS.items():
            writer(daily_sales(branch, 2026, month), month, OUT)
    print(f"{len(list(OUT.iterdir()))} files written to {OUT}")


if __name__ == "__main__":
    main()
